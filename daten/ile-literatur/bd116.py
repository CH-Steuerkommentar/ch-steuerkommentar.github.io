def jahr(zitat):
    import re
    j = [int(x) for x in re.findall(r"\b(19\d\d|20\d\d)\b", zitat)]
    if j:
        return max(j)
    m = re.search(r"ASA (\d+),", zitat)  # ASA-Band ohne Jahr: Bd. 1 = 1932/33
    return 1931 + int(m.group(1)) if m else None

